func (t TokenType) String() string {
	names := [...]string{
		"LEFT_PAREN", "RIGHT_PAREN", "LEFT_BRACE", "RIGHT_BRACE",
		"COMMA", "DOT", "MINUS", "PLUS", "SEMICOLON", "STAR", "PERCENT",
		"SLASH", "BANG", "BANG_EQUAL", "EQUAL", "EQUAL_EQUAL",
		"GREATER", "GREATER_EQUAL", "LESS", "LESS_EQUAL",
		"IDENTIFIER", "STRING", "NUMBER",
		"AND", "CLASS", "ELSE", "FALSE", "FUN", "FOR", "IF", "NIL", "OR",
		"PRINT", "RETURN", "SUPER", "THIS", "TRUE", "VAR", "WHILE",
		"EOF",
	}
	if int(t) < 0 || int(t) >= len(names) {
		return fmt.Sprintf("UNKNOWN(%d)", int(t))
	}
	return names[t]
}

// TOKEN
type Token struct {
	TokenType TokenType
	Lexeme    string
	Literal   any
	Line      int
}

// NewToken crea un nuevo token con el tipo y lexema indicados
func NewToken(tokenType TokenType, lexeme string, literal any, line int) *Token {
	return &Token{
		TokenType: tokenType,
		Lexeme:    lexeme,
		Literal:   literal,
		Line:      line,
	}
}

func (t Token) String() string {
	if t.TokenType == IDENTIFIER {
		return fmt.Sprintf("%s<%s>", t.TokenType, t.Lexeme)
	} else if t.Literal != nil {
		return fmt.Sprintf("%s<%v>", t.TokenType, t.Literal)
	}
	return t.TokenType.String()
}
